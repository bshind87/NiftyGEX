"""Render docs/findings_t2.md from the results store (all numbers come from stored runs)."""
from __future__ import annotations

import json
from pathlib import Path

import polars as pl

from niftygex.config import REPO_ROOT
from niftygex_eval.config import load_eval_config


def latest_runs(root: Path) -> dict[tuple[str, str], str]:
    latest: dict[tuple[str, str], str] = {}
    for line in (root / "index.jsonl").read_text().splitlines():
        record = json.loads(line)
        latest[(record["stage"], record["model"])] = record["run_id"]
    return latest


def f(value, digits: int = 3) -> str:
    if value is None:
        return "—"
    return f"{value:.{digits}f}" if isinstance(value, float) else str(value)


def table(rows: list[dict], columns: list[tuple[str, str]], digits: int = 3) -> str:
    out = ["| " + " | ".join(label for _, label in columns) + " |", "|" + "---|" * len(columns)]
    out += ["| " + " | ".join(f(row.get(key), digits) for key, _ in columns) + " |" for row in rows]
    return "\n".join(out)


def f2_reading(holm: dict) -> list[str]:
    """F1/F2 narrative with numbers from the Holm results."""
    f2 = {m["test"].split(" (")[0]: m for m in holm["F2"]["members"]}
    f1 = {m["test"]: m for m in holm["F1"]["members"]}
    c, c1, c2 = f2["C vs B"], f2["C1 vs B"], f2["C2 vs B"]
    primary = f1["inferred sign, full"]
    return [
        f"- **Levels, not GEX magnitude, carry the C gain.** On IC, C2 (levels + concentration) improves on B by {f(c2['estimate'], 4)} "
        f"(wins {c2['wins']}, p {f(c2['p'])}), as much as the full set C does ({f(c['estimate'], 4)}, p {f(c['p'])}). C1 (normalized GEX + inferred "
        f"sign) adds {f(c1['estimate'], 4)} (p {f(c1['p'])}).",
        f"- **After Holm within F2, no comparison is significant at 5%.** C vs B has Holm p {f(c['p_holm'])} and C2 vs B has {f(c2['p_holm'])}. "
        "These are suggestive, not confirmed.",
        f"- **F1 inferred-sign result:** full-sample coefficient {f(primary['estimate'])}, Holm p {f(primary['p_holm'])} "
        f"({'survives' if primary['reject_holm'] else 'does not survive'} at 5%). Sign terms rejecting under Holm: "
        + (", ".join(m["test"] for m in holm["F1"]["members"] if m["reject_holm"]) or "none") + ".",
        "- **SHAP agrees with the ablation.** Vol-state features dominate. Among GEX/levels features, max-pain distance and GEX concentration "
        "rank highest. SHAP measures use, not incremental value, so participant features can rank high in SHAP while adding nothing in the ablation.",
    ]


def main() -> None:
    cfg = load_eval_config()
    root = Path(cfg["results_root"])
    runs = latest_runs(root)
    stage_a_id = runs[("stage_a", "ols_hac")]
    regressions = pl.read_parquet(root / "runs" / stage_a_id / "regressions.parquet")
    comparison = json.loads((root / "stage_b_t2_comparison.json").read_text())
    ablation = json.loads((root / "t2_ablation.json").read_text())
    holm = {fam["family"]: fam for fam in json.loads((root / "multiple_testing.json").read_text())["families"]}
    figures = json.loads((root / "figures" / "index.json").read_text()) if (root / "figures" / "index.json").exists() else []
    samples = {"full": "full", "pre_weekly_expiry_rationalisation": "pre", "post_weekly_expiry_rationalisation": "post"}

    def a_rows(spec: str, controls: str, terms: list[str] | None = None) -> list[dict]:
        part = regressions.filter((pl.col("spec") == spec) & (pl.col("controls") == controls) & pl.col("is_gex_term") & pl.col("sample").is_in(list(samples)))
        if terms:
            part = part.filter(pl.col("term").is_in(terms))
        return [{**row, "sample": samples[row["sample"]]} for row in part.sort("convention", "term", "sample").to_dicts()]

    controls_full = regressions.filter((pl.col("spec") == "normalized") & (pl.col("controls") == "full_controls")
                                       & (pl.col("convention") == "absolute") & (pl.col("sample") == "full")).to_dicts()
    a_columns = [("convention", "convention"), ("term", "term"), ("sample", "sample"), ("n", "n"), ("coef", "coef"), ("t", "t (HAC)"), ("p", "p"), ("r2", "R²")]
    stage_b_ids = {model: run for (stage, model), run in runs.items() if stage == "stage_b"}
    ablation_tests = [{"comparison": name.replace("_vs_", " vs "), "metric": metric, **values}
                      for name, block in ablation["paired_tests"].items() for metric, values in block.items()]
    lines = [
        "# T2 findings: does dealer gamma explain next-day volatility?",
        "",
        "Generated by `scripts/write_findings_t2.py` from the results store (`outputs/results/`); every number below comes from a stored run. "
        f"Data config hash `{comparison['data_config_hash'][:12]}`, eval config hash `{comparison['eval_config_hash'][:12]}`.",
        "",
        "**Target.** T2 compares next-day realized volatility with its trailing 20-day level, measured from front-month futures 5-minute returns "
        "(intraday only) at the 15:15 snapshot. Labels are causal terciles and start in 2020. See `docs/schema.md`.",
        "",
        "## 1. Stage A: regressions on total GEX",
        "",
        "Every regression is HAC (Newey–West) OLS of the next-day RV ratio on normalized total GEX. Normalized GEX is total GEX divided by its causal "
        "trailing mean absolute level, which removes the OI growth trend.",
        "",
        "### With the India VIX control only",
        "",
        "The absolute convention looks strong here.",
        "",
        table(a_rows("normalized", "vix"), a_columns),
        "",
        "### With full controls",
        "",
        "Here the controls are previous VIX, ATM IV, days to expiry, the expiry-day flag, and today's RV ratio.",
        "",
        table(a_rows("normalized", "full_controls"), a_columns),
        "",
        "**Finding: the magnitude effect was confounding.** Once implied volatility, the expiry calendar and today's RV ratio are controlled for, "
        "the GEX-magnitude coefficient is no longer distinguishable from zero. Gamma is mechanically larger when IV is low and when expiry is near, "
        "and those variables, not dealer hedging per se, explain the VIX-only association. Coefficients of the controls in the full-sample "
        "absolute-convention regression:",
        "",
        table(controls_full, [("term", "term"), ("coef", "coef"), ("t", "t (HAC)"), ("p", "p")]),
        "",
        "### Joint specification: magnitude plus sign, with full controls",
        "",
        table(a_rows("joint_magnitude_sign", "full_controls"), a_columns),
        "",
        "**Finding: the inferred sign adds information beyond magnitude; the naive sign does not.** When the Pro dealer proxy is net long gamma "
        "(positive inferred total GEX), the next-day RV ratio is lower, the direction the dampening hypothesis predicts. The effect holds before the "
        "weekly-expiry rationalisation marker but is not significant after it, on a much smaller post sample. "
        "The inferred sign comes from daily participant OI covering all index options, so it may proxy participant positioning rather than "
        "NIFTY gamma itself.",
        "",
        f"Stage A run: `{stage_a_id}`.",
        "",
        "## 2. Stage B: tercile classifiers in the walk-forward harness",
        "",
        f"There are {comparison['walks']} expiry-aligned walks: expanding training window, one-cycle embargo, label purge, no shuffling. "
        "The reference model is tuned LightGBM with Platt calibration.",
        "",
        table(comparison["comparison_table"], [("model", "model"), ("auc_pooled", "AUC pooled"), ("auc_mean_per_walk", "AUC mean/walk"),
                                               ("brier", "Brier"), ("log_loss", "log loss"), ("ece_mean", "ECE")]),
        "",
        "**Findings**",
        "",
        "- **VIX alone has no skill**, because the target is relative to its own trailing level.",
        "- **Untuned models are overconfident.** Their Brier score is no better than the class-frequency prior.",
        "- **Regularization fixes most of the calibration.** It is chosen on a time-ordered inner validation split.",
        "- **Platt scaling then makes the reference model beat the prior** on Brier in most walks.",
        "",
        "Paired per-walk tests (A vs B):",
        "",
        table([{"comparison": k, **v} for k, v in comparison["paired"].items()],
              [("comparison", "comparison"), ("mean_a", "mean A"), ("mean_b", "mean B"), ("mean_diff", "diff"), ("t_paired", "t"), ("a_wins", "A wins"), ("walks", "walks")], 4),
        "",
        "Run ids: " + ", ".join(f"{model} `{run}`" for model, run in sorted(stage_b_ids.items())) + ".",
        "",
        "## 3. Ablation (tuned LightGBM + Platt; regression for the continuous variant)",
        "",
        "The three feature sets are nested:",
        "",
        "- **A:** vol state and calendar.",
        "- **B:** A plus participant positioning.",
        "- **C:** B plus normalized GEX and levels.",
        "- **C1:** B plus normalized GEX (3 conventions) and the inferred sign.",
        "- **C2:** B plus levels (call wall, put wall, naive flip, max pain, max-GEX strike distances) and GEX concentration.",
        "",
        "The continuous variant predicts log(next-day RV ratio) and is scored by the per-walk Spearman information coefficient (IC).",
        "",
        table(ablation["comparison_table"], [("feature_set", "set"), ("features", "features"), ("auc_mean_per_walk", "AUC mean/walk"), ("brier", "Brier"),
                                             ("ece_mean", "ECE"), ("ic_mean_per_walk", "IC mean/walk"), ("ic_positive_walks", "IC>0 walks"), ("regression_walks", "walks")]),
        "",
        table(ablation_tests, [("comparison", "comparison"), ("metric", "metric"), ("mean_a", "mean A"), ("mean_b", "mean B"), ("mean_diff", "diff"),
                               ("t_paired", "t"), ("a_wins", "A wins"), ("walks", "walks")], 4),
        "",
        "**Findings**",
        "",
        "### Holm-adjusted families",
        "",
        "F2 is the primary family (IC). AUC and Brier get their own secondary families.",
        "",
        *[part for name in ("F2", "F2-secondary-AUC", "F2-secondary-Brier") for part in (
            f"**{name}**", "",
            table(holm[name]["members"], [("test", "test"), ("estimate", "mean diff"), ("t", "t"), ("wins", "wins"), ("p", "p"), ("p_holm", "Holm p"), ("reject_holm", "reject")], 4),
            "")],
        "**F1, Stage A sign terms** (primary: full-sample inferred sign):",
        "",
        table(holm["F1"]["members"], [("test", "test"), ("estimate", "coef"), ("t", "t"), ("p", "p"), ("p_holm", "Holm p"), ("primary", "primary"), ("reject_holm", "reject")]),
        "",
        "### Feature importance (TreeSHAP on the tuned model's raw output for set " + ablation.get("shap_feature_set", "C") + ")",
        "",
        "Mean |SHAP| is computed per walk, then averaged across walks (classification: averaged over the three tercile outputs).",
        "",
        table(sorted([r for r in ablation.get("shap_mean_abs", {}).get("classification", []) if r["output"] == "all_outputs"],
                     key=lambda r: -r["mean_abs_shap"])[:12],
              [("feature", "feature"), ("mean_abs_shap", "mean |SHAP|"), ("sd_across_walks", "sd across walks"), ("walks", "walks")], 4),
        "",
        "Figures (in the results store): " + ", ".join(f"`{fig}`" for fig in figures) + ".",
        "",
        "**Findings**",
        "",
        "- **Participant positioning adds nothing** over vol state and calendar (B vs A).",
        *f2_reading(holm),
        "- **Most of the predictability comes from vol-state features**, chiefly volatility mean reversion.",
        "- **Caveat:** with about 20 walks and several comparisons, t-statistics around 2 are modest evidence.",
        "",
        "Run ids: " + ", ".join(f"{name}: classification `{ids['classification']}`, regression `{ids['regression']}`" for name, ids in ablation["runs"].items()) + ".",
        "",
    ]
    out = REPO_ROOT / "docs" / "findings_t2.md"
    out.write_text("\n".join(lines))
    print(out)


if __name__ == "__main__":
    main()
