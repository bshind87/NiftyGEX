"""Deterministic Markdown rendering of the validation report payload."""
from __future__ import annotations

from typing import Any


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def _table(rows: list[dict[str, Any]], columns: list[str] | None = None) -> str:
    if not rows:
        return "_none_\n"
    columns = columns or list(rows[0])
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(_fmt(row.get(column)) for column in columns) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def render_markdown(payload: dict[str, Any]) -> str:
    parity, iv, vix = payload["parity_residuals"], payload["call_put_iv_agreement"], payload["atm_iv_vs_india_vix"]
    gamma, lots = payload["gamma_sanity"], payload["lot_sizes"]
    out = [
        "# Validation report",
        "",
        "Generated by `scripts/validate_data.py` from stage outputs; do not edit by hand. Machine-readable copy: "
        "`outputs/reports/validation_report.json`.",
        "",
        f"**All timestamp/leakage checks passed:** {_fmt(payload['all_leakage_checks_passed'])}",
        "",
        "## Parity residuals",
        "",
        parity["definition"] + ".",
        "",
        _table([{"scope": "all", **parity["overall"]}] + [{"scope": row["year"], **{k: v for k, v in row.items() if k != "year"}} for row in parity["by_year"]]),
        "Forward quality by year (snapshots):",
        "",
        _table(parity["forward_quality_by_year"]),
        "## Call vs put IV agreement",
        "",
        iv["definition"] + ". Values are absolute IV differences (0.01 = 1 vol point).",
        "",
        _table([{"scope": "all", **iv["overall"]}] + [{"scope": row["year"], **{k: v for k, v in row.items() if k != "year"}} for row in iv["by_year"]]),
        "By |log moneyness|:",
        "",
        _table(iv["by_moneyness"]),
        "## ATM IV vs India VIX",
        "",
        vix["definition"] + ".",
        "",
        _table([{"scope": "all", **vix["overall"]}] + [{"scope": row["year"], **{k: v for k, v in row.items() if k != "year"}} for row in vix["by_year"]]),
        "By days to the longest available expiry:",
        "",
        _table(vix["by_days_to_longest_expiry"]),
        "## Gamma sanity",
        "",
        f"Max-gamma strike within one strike of the forward (nearest expiry): {_fmt(gamma['max_gamma_near_forward']['nearest_expiry']['share'])}; "
        f"all expiries: {_fmt(gamma['max_gamma_near_forward']['all_expiries']['share'])}.",
        "",
        _table(gamma["max_gamma_near_forward"]["nearest_expiry_by_dte"]),
        "ATM gamma x forward by days to expiry (nearest expiry); monotone decreasing: "
        f"{_fmt(gamma['atm_gamma_vs_time_to_expiry']['median_gamma_x_forward_monotone_decreasing_in_dte'])}.",
        "",
        _table(gamma["atm_gamma_vs_time_to_expiry"]["by_dte"]),
        "## Lot sizes",
        "",
        f"Expiries judged: {lots['expiries_judged']}; failed: {lots['expiries_failed']}; without positive OI: {lots['expiries_without_positive_oi']}.",
        "",
        _table(lots["exceptions"]),
        "## Bhavcopy reconciliation",
        "",
        f"Status: {payload['bhavcopy_reconciliation']['status']} — {payload['bhavcopy_reconciliation']['reason']}.",
        "",
        "## Timestamp and leakage checks",
        "",
        _table(payload["timestamp_and_leakage_checks"], ["check", "passed", "violations"]),
        "Leakage test modules (`" + "`, `".join(payload["leakage_test_run"]["modules"]) + "`): "
        f"passed = {_fmt(payload['leakage_test_run']['passed'])}, counts = {payload['leakage_test_run']['counts']}.",
        "",
    ]
    return "\n".join(out)
