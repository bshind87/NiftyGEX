"""Explorer HPC job list, SLURM scripts and the submission plan for the exploratory neural runs (docs/hpc.md).

One job per experiment, model, horizon and seed; every job trains all walks of one run with per-walk checkpoints,
so a job stopped by the 8-hour limit is resubmitted and resumes. Seeds are merged afterwards on the Mac
(scripts/merge_seeds.py). The scheduler keeps each partition within its running/submitted limits.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Any

# Exit codes of a killed job (time limit, preemption): resubmit, never mark failed. 75 is a walk-limit exit.
RESUBMIT_CODES = {75, 137, 143}


@dataclass(frozen=True)
class Job:
    name: str
    wave: str
    command: str
    calibration: bool = False


def job_list(seeds: list[int], horizons: list[int]) -> list[Job]:
    """Every exploratory GPU job, in submission priority: calibration, L = 12 references, E1, E3, E2 (L = 72 last)."""
    jobs = [Job("cal_t2_l12", "calibration", "scripts/run_neural.py --models attention_gru --walks 2 --seed 11 --label hpccal", True),
            Job("cal_e3_1h", "calibration", "scripts/run_intraday.py --horizon 1 --models attention_gru --walks 2 --seed 11", True)]
    for seed in seeds:
        for model in ("attention_gru", "deepsets", "attention"):
            jobs.append(Job(f"ref_{model}_l12_s{seed}", "references", f"scripts/run_neural.py --models {model} --seed {seed} --label hpc"))
    for seed in seeds:
        for part in ("hybrid", "residual_attention", "residual_deepsets", "state_mlp"):
            jobs.append(Job(f"e1_{part}_s{seed}", "e1", f"scripts/run_exploratory_e1.py --parts {part} --seed {seed}"))
    for horizon in horizons:
        for seed in seeds:
            for model in ("attention_gru", "attention", "deepsets"):
                jobs.append(Job(f"e3_{model}_{horizon}h_s{seed}", "e3", f"scripts/run_intraday.py --horizon {horizon} --models {model} --seed {seed}"))
    for seed in seeds:
        jobs.append(Job(f"e2_window24_s{seed}", "e2", f"scripts/run_neural.py --models attention_gru --window 24 --seed {seed} --label hpc"))
        for days in (5, 10):
            jobs.append(Job(f"e2_multiday{days}_s{seed}", "e2", f"scripts/run_exploratory_e2.py --days {days} --seed {seed}"))
    for seed in seeds:
        jobs.append(Job(f"e2_window72_s{seed}", "e2_l72", f"scripts/run_neural.py --models attention_gru --window 72 --seed {seed} --label hpc"))
    return jobs


def render_script(job: Job, settings: dict[str, Any], gpu_type: str) -> str:
    """The sbatch script of one job (partition chosen at submission; calibration jobs pin gpu-short)."""
    resources, scratch, code = settings["resources"], settings["scratch_dir"], settings["code_dir"]
    time_limit = settings["calibration"]["time"] if job.calibration else resources["time"]
    status = f"{scratch}/outputs/hpc/status/{job.name}"
    return f"""#!/bin/bash
# {job.wave}: {job.name} (generated by hpc/make_jobs.py; partition set by hpc/scheduler.py at submission)
#SBATCH --job-name={settings['job_prefix']}{job.name}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --gres=gpu:{gpu_type}:1
#SBATCH --cpus-per-task={resources['cpus_per_task']}
#SBATCH --mem={resources['mem']}
#SBATCH --time={time_limit}
#SBATCH --output={scratch}/outputs/hpc/logs/%x_%j.log
set -u
module purge
module load {' '.join(settings['modules'])}
source activate {settings['env_dir']}
cd {code}
export NIFTYGEX_PROFILE=hpc NIFTYGEX_DEVICE=cuda NIFTYGEX_GPU_TYPE={gpu_type} PYTHONPATH=src
echo "job $SLURM_JOB_ID on $(hostname), partition $SLURM_JOB_PARTITION, commit $(git rev-parse --short HEAD)"
nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader
python {job.command}
code=$?
# A run that finished writes .done; a crash writes .failed; a job killed at the time limit writes nothing and is
# resubmitted by the scheduler, resuming from its walk checkpoints.
if [ $code -eq 0 ]; then
    touch {status}.done
elif ! echo " {' '.join(str(c) for c in sorted(RESUBMIT_CODES))} " | grep -q " $code "; then
    echo "$code" > {status}.failed
fi
sacct -j "$SLURM_JOB_ID" --format=JobID,Elapsed,MaxRSS,State --noheader || true
exit $code
"""


def plan_submissions(jobs: list[Job], queued: dict[str, str], done: set[str], failed: set[str], attempts: dict[str, int],
                     partitions: list[dict[str, Any]], calibration: dict[str, Any], max_attempts: int,
                     queue_counts: dict[str, int]) -> tuple[list[tuple[Job, str]], list[str]]:
    """Which jobs to submit now and where, in list order; also the jobs that ran out of attempts.

    ``queued``: job name -> partition of our jobs still running or pending. ``queue_counts``: our submitted jobs per
    partition. A partition takes jobs while its submitted count is below ``max_submitted``.
    """
    counts = dict(queue_counts)
    plan, exhausted = [], []
    for job in jobs:
        if job.name in done or job.name in failed or job.name in queued:
            continue
        if attempts.get(job.name, 0) >= max_attempts:
            exhausted.append(job.name)
            continue
        options = [{"name": calibration["partition"], "max_submitted": calibration["max_submitted"]}] if job.calibration else partitions
        for partition in options:
            if counts.get(partition["name"], 0) < int(partition["max_submitted"]):
                plan.append((job, partition["name"]))
                counts[partition["name"]] = counts.get(partition["name"], 0) + 1
                break
    return plan, exhausted


def expand(value: str) -> str:
    return os.path.expandvars(value)
